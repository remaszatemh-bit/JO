-- Supabase setup for the Jordan Tourism GitHub Pages site
-- Paste this entire script into Supabase SQL Editor and run it once.

create table if not exists public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    name text not null default '',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles for
select to authenticated using (auth.uid () = id);

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own" on public.profiles for
insert
    to authenticated
with
    check (auth.uid () = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles for
update to authenticated using (auth.uid () = id)
with
    check (auth.uid () = id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''))
  on conflict (id) do update set
    name = excluded.name,
    updated_at = now();
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create table if not exists public.user_favorites (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    favorite_key text not null,
    title text not null,
    governorate text not null,
    created_at timestamptz not null default now(),
    unique (user_id, favorite_key)
);

alter table public.user_favorites enable row level security;

drop policy if exists "favorites_select_own" on public.user_favorites;
create policy "favorites_select_own" on public.user_favorites for
select to authenticated using (auth.uid () = user_id);

drop policy if exists "favorites_insert_own" on public.user_favorites;
create policy "favorites_insert_own" on public.user_favorites for
insert
    to authenticated
with
    check (auth.uid () = user_id);

drop policy if exists "favorites_delete_own" on public.user_favorites;
create policy "favorites_delete_own" on public.user_favorites for delete to authenticated using (auth.uid () = user_id);

drop policy if exists "favorites_update_own" on public.user_favorites;
create policy "favorites_update_own" on public.user_favorites for
update to authenticated using (auth.uid () = user_id)
with
    check (auth.uid () = user_id);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;

create trigger profiles_set_updated_at
before update on public.profiles
for each row execute procedure public.set_updated_at();

-- Allow the browser client to use only the operations protected by the RLS policies above.
grant
select,
insert
,
update on
table public.profiles to authenticated;

grant
select,
insert
,
update,
delete on
table public.user_favorites to authenticated;
